function getInitialLocale(): Locale {
    if (typeof window === 'undefined') return 'en';
    const saved = window.localStorage.getItem('famlyr.locale');
    if (saved === 'en' || saved === 'cs') return saved;
    return window.navigator.language.toLowerCase().startsWith('cs') ? 'cs' : 'en';
}

let locale = $state<Locale>(getInitialLocale());

export function getLocale(): Locale {
    return locale;
}

export function setLocale(nextLocale: Locale) {
    locale = nextLocale;
    if (typeof window !== 'undefined') {
        window.localStorage.setItem('famlyr.locale', nextLocale);
        document.documentElement.lang = nextLocale;
    }
}

export function t(key: keyof typeof translations.en, params?: Record<string, string | number>): string {
    let value = translations[locale][key];
    if (!params) return value;
    for (const [name, replacement] of Object.entries(params)) {
        value = value.replaceAll(`{${name}}`, String(replacement));
    }
    return value;
}
